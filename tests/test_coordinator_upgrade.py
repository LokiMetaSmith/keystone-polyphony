"""Upgrade real PR96 records without rewriting evidence, work, or task budgets.

The fixture was generated by coordinator.py from commit 907a1f1, not by the
current implementation. Its source commit and SHA256 are recorded in the JSON.
"""

import json
from pathlib import Path

from aiohttp.test_utils import TestClient, TestServer
import pytest

from src.liminal_bridge.coordinator import Conflict, Coordinator
from src.liminal_bridge.coordinator_service import create_app


@pytest.fixture
def legacy(tmp_path):
    saved = json.loads(
        (Path(__file__).parent / "fixtures/coordinator-pr96.json").read_text()
    )
    store = Coordinator(
        tmp_path / "upgrade.db",
        clock=lambda: 100.0,
        monotonic_clock=lambda: 500.0,
        boot_id="current-boot",
    )
    with store.connect() as db:
        db.executemany(
            "INSERT INTO records VALUES(?,?,?)",
            [(r["kind"], r["id"], json.dumps(r["body"])) for r in saved["records"]],
        )
        db.executemany(
            "INSERT INTO artifacts VALUES(?,?)",
            [(r["id"], r["content"].encode()) for r in saved["artifacts"]],
        )
        db.executemany("INSERT INTO events VALUES(?,?,?,?)", saved["events"])
    return store, saved


def test_upgrade_preserves_valid_admission_artifacts_and_historical_records(legacy):
    store, saved = legacy
    root = saved["cases"]["independent"]
    expected = next(
        r["body"]
        for r in saved["records"]
        if r["kind"] == "admission" and r["id"] == root["candidate"]
    )
    assert "dependency_admissions" not in expected["candidate"]
    assert store.admission(root["candidate"]) == expected
    before = store.cursor()
    snapshot = store.snapshot()
    root_task = next(t for t in snapshot["task"] if t["id"] == root["task"])
    assert root_task["status"] == "accepted"
    for artifact in saved["artifacts"]:
        assert store.artifact(artifact["id"]) == artifact["content"]
    with store.connect() as db:
        actual = [
            {"kind": k, "id": i, "body": json.loads(b)}
            for k, i, b in db.execute(
                "SELECT kind,id,body FROM records ORDER BY kind,id"
            )
        ]
    assert actual == saved["records"]
    assert store.cursor() == before == saved["events"][-1][0]


@pytest.mark.asyncio
@pytest.mark.parametrize("case", ["dependent", "symbolic"])
async def test_incompatible_admission_has_owner_controlled_upgrade_with_new_review(
    legacy, case
):
    store, saved = legacy
    old = saved["cases"][case]
    snapshot = store.snapshot()
    original = next(t for t in snapshot["task"] if t["id"] == old["task"])
    assert original["status"] == "blocked"
    assert original["admission_invalid"]
    credentials = {
        letter * 32: {"identity": identity, "role": role}
        for letter, identity, role in [
            ("o", "owner", "owner"),
            ("a", "author", "worker"),
            ("r", "reviewer", "reviewer"),
        ]
    }
    async with TestClient(TestServer(create_app(store, credentials))) as client:

        async def call(op, token, **payload):
            return await client.post(
                "/call/" + op,
                json=payload,
                headers={"Authorization": "Bearer " + token * 32},
            )

        assert (
            await call("admission", "o", candidate_id=old["candidate"])
        ).status == 409
        assert (await call("accept", "o", candidate_id=old["candidate"])).status == 409
        revision = dict(
            task_id=old["task"],
            expected_revision=1,
            requirements=original["requirements"],
            checks=original["checks"],
            reviewers=original["reviewers"],
        )
        assert (await call("revise", "a", **revision)).status == 403
        revised = await call("revise", "o", **revision)
        assert revised.status == 200
        revised_task = (await revised.json())["result"]
        assert revised_task["attempts"] == 1 and revised_task["allocated_seconds"] == 10
        attempt_response = await call(
            "start_attempt",
            "a",
            task_id=old["task"],
            capabilities=[],
            seconds=10,
            request_key="upgrade-" + case,
        )
        assert attempt_response.status == 200
        attempt = (await attempt_response.json())["result"]
        content = store.artifact(old["artifact"])
        work = await call("save_work", "a", attempt_id=attempt["id"], content=content)
        assert (await work.json())["result"] == old["artifact"]
        candidate_response = await call(
            "candidate",
            "a",
            attempt_id=attempt["id"],
            base=saved["source_commit"],
            artifact_id=old["artifact"],
        )
        candidate = (await candidate_response.json())["result"]
        assert candidate["id"] != old["candidate"]
        assert (await call("accept", "o", candidate_id=candidate["id"])).status == 409
        evidence = dict(
            candidate_id=candidate["id"],
            check="tests",
            passed=True,
            input_revision=2,
            request_key="upgrade-review-" + case,
        )
        assert (await call("evidence", "a", **evidence)).status == 403
        assert (await call("evidence", "r", **evidence)).status == 200
        accepted = await call("accept", "o", candidate_id=candidate["id"])
        assert accepted.status == 200
        packet = (await accepted.json())["result"]
        assert store.admission(candidate["id"]) == packet
        assert packet["candidate"]["revision"] == 2
        assert store.artifact(old["artifact"]) == content
        with pytest.raises(Conflict):
            store.admission(old["candidate"])
        migrated = next(t for t in store.snapshot()["task"] if t["id"] == old["task"])
        assert migrated["attempts"] == 2 and migrated["allocated_seconds"] == 20


def test_legacy_attempt_recovery_preserves_fences_retry_receipts_and_budgets(legacy):
    store, saved = legacy
    reserved = saved["cases"]["reserved"]
    unknown = saved["cases"]["unknown"]
    # The old wall-clock lease still looks live, but cannot grant new permission.
    assert store.snapshot()["resource"][0]["until"] > 100
    assert not store.snapshot()["resource"][0]["lease_current"]
    with pytest.raises(Conflict):
        store.write_resource(
            "shared", reserved["attempt"], "author", 1, "new-old-write", {}
        )
    assert store.request_cancel(reserved["attempt"], "author")["termination_confirmed"]
    replacement = store.start_attempt(
        reserved["task"], "author", [], 10, "upgrade-reserved"
    )
    lease = store.acquire("shared", replacement["id"], "author", 1, seconds=5)
    assert lease["fence"] == 2
    effect = store.write_resource(
        "shared", replacement["id"], "author", 2, "new-write", {"upgraded": True}
    )
    assert (
        store.write_resource(
            "shared", reserved["attempt"], "author", 1, "old-write", {"legacy": True}
        )
        == reserved["effect"]
    )
    assert store.snapshot()["destination"] == [effect]
    assert not store.request_cancel(unknown["attempt"], "author")[
        "termination_confirmed"
    ]
    with pytest.raises(Conflict):
        store.start_attempt(unknown["task"], "author", [], 10, "unsafe-retry")
    assert store.artifact(unknown["artifact"]) == "legacy partial work\n"
    # In production the owner must independently verify death before this call.
    store.observe(unknown["attempt"], "exited", True)
    assert (
        store.start_attempt(unknown["task"], "author", [], 10, "verified-retry")[
            "number"
        ]
        == 2
    )
    for case in (reserved, unknown):
        task = next(t for t in store.snapshot()["task"] if t["id"] == case["task"])
        assert task["attempts"] == 2 and task["allocated_seconds"] == 20


def test_legacy_unchanged_review_retry_keeps_its_admission(legacy):
    store, saved = legacy
    root = saved["cases"]["independent"]
    packet = store.admission(root["candidate"])
    result = store.evidence(root["candidate"], "reviewer", "tests", True, 1)
    assert result in packet["evidence"]
    assert store.admission(root["candidate"]) == packet
    with pytest.raises(Conflict, match="request_key"):
        store.evidence(root["candidate"], "reviewer", "tests", False, 1)
    store.evidence(
        root["candidate"], "reviewer", "tests", False, 1, request_key="fresh-failure"
    )
    with pytest.raises(Conflict):
        store.admission(root["candidate"])
    store.evidence(
        root["candidate"], "reviewer", "tests", True, 1, request_key="fresh-recheck"
    )
    assert store.accept(root["candidate"])["candidate"] == packet["candidate"]
